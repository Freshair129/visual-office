function surfaceBoundaryEdges(file,primitive){
 // UV seams duplicate glTF vertices but are not holes in the physical surface.
 // The first recipe incorrectly decimated those UV islands independently.
 const positions=accessor(file,primitive.attributes.POSITION).map(p=>p.join(','));
 const indices=primitive.indices===undefined?positions.map((_,i)=>i):accessor(file,primitive.indices).flat();
 const edges=new Map();
 for(let i=0;i<indices.length;i+=3)for(let j=0;j<3;j++){
  const a=positions[indices[i+j]],b=positions[indices[i+(j+1)%3]];if(a===b)continue;
  const key=a<b?a+'|'+b:b+'|'+a;edges.set(key,(edges.get(key)||0)+1);
 }
 return [...edges.values()].filter(n=>n===1).length;
}

