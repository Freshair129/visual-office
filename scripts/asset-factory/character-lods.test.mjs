function glb(bytes){
 assert.equal(bytes.readUInt32LE(0),0x46546c67);assert.equal(bytes.readUInt32LE(4),2);assert.equal(bytes.readUInt32LE(8),bytes.length);
 const size=bytes.readUInt32LE(12);assert.equal(bytes.readUInt32LE(16),0x4e4f534a);
 const doc=JSON.parse(bytes.subarray(20,20+size));assert.equal(bytes.readUInt32LE(24+size),0x004e4942);
 assert.equal(28+size+bytes.readUInt32LE(20+size),bytes.length);
 return {doc,binary:bytes.subarray(28+size)};
}
function view({doc,binary},index){
 const v=doc.bufferViews[index];assert.equal(v.buffer,0);assert.equal(v.extensions,undefined);
 const offset=v.byteOffset||0;assert.ok(offset>=0&&offset+v.byteLength<=binary.length);
 return binary.subarray(offset,offset+v.byteLength);
}
function accessor(file,index){
 const {doc}=file,a=doc.accessors[index],v=doc.bufferViews[a.bufferView];assert.equal(a.sparse,undefined);
 const [read,bytes]=({5120:['readInt8',1],5121:['readUInt8',1],5122:['readInt16LE',2],5123:['readUInt16LE',2],5125:['readUInt32LE',4],5126:['readFloatLE',4]})[a.componentType];
 const width=({SCALAR:1,VEC2:2,VEC3:3,VEC4:4,MAT4:16})[a.type],raw=view(file,a.bufferView),stride=v.byteStride||width*bytes;
 return Array.from({length:a.count},(_,row)=>Array.from({length:width},(_,column)=>raw[read]((a.byteOffset||0)+row*stride+column*bytes)));
}
function triangles(doc){
 return doc.meshes.reduce((total,mesh)=>total+mesh.primitives.reduce((n,p)=>{
  assert.equal(p.mode??4,4);const count=doc.accessors[p.indices??p.attributes.POSITION].count;assert.equal(count%3,0);return n+count/3;
 },0),0);
}
